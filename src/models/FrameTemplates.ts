/** Native frame types that have known default templates. */
export type TemplateFrameType = keyof typeof FrameTemplates;

/** Every known loaded or unloaded default template for a native frame type, e.g. FrameTemplate<"BACKDROP">. */
export type FrameTemplate<Type extends TemplateFrameType> = (typeof FrameTemplates)[Type]["loaded" | "unloaded"][number];

/**
 * Suggests the known templates for autocomplete while still accepting any string.
 * (string & {}) keeps the literal suggestions from collapsing into string.
 */
export type InheritsOf<Template extends string> = Template | (string & {});
